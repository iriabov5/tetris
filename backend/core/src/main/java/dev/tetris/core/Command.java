package dev.tetris.core;

/**
 * Действия ядра, вызываемые управлением или таймером падения.
 */
public enum Command {
    /**
     * Сдвиг на одну клетку влево.
     */
    LEFT,
    /**
     * Сдвиг на одну клетку вправо.
     */
    RIGHT,
    /**
     * Поворот по контракту конкретного типа.
     */
    ROTATE,
    /**
     * Шаг вниз или закрепление при невозможном сдвиге.
     */
    DOWN,
    /**
     * Мгновенное опускание до препятствия с закреплением и выпуском следующей фигуры.
     */
    HARD_DROP
}
