package dev.tetris.core;

/**
 * Точка подключения порядка выдачи фигур к независимому алгоритму партии.
 */
@FunctionalInterface
public interface PieceSource {
    /**
     * Предоставляет очередной тип для выпуска фигуры.
     * Рабочая реализация должна возвращать ненулевое допустимое определение.
     *
     * @return определение следующей фигуры
     */
    Tetromino next();
}
