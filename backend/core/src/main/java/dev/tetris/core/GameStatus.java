package dev.tetris.core;

/**
 * Жизненный цикл партии, определяемый возможностью выпуска очередной фигуры.
 */
public enum GameStatus {
    /**
     * На поле есть активная фигура для следующих команд.
     */
    RUNNING,
    /**
     * Очередная фигура не поместилась в стартовой позиции.
     */
    GAME_OVER
}
