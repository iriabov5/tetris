package dev.tetris.core;

/**
 * Неизменяемая координата локального шаблона или игрового поля.
 *
 * @param x координата по горизонтали, растущая вправо
 * @param y координата по вертикали, растущая вниз
 */
public record Cell(int x, int y) {
    /**
     * Создаёт координату со смещением для расчёта кандидата хода.
     *
     * @param dx смещение по горизонтали
     * @param dy смещение по вертикали
     * @return новая клетка без изменения исходной
     */
    public Cell translated(int dx, int dy) {
        return new Cell(x + dx, y + dy);
    }
}
