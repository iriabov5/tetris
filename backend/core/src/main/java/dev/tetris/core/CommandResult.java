package dev.tetris.core;

/**
 * Исход обработки одной команды относительно текущего состояния партии.
 */
public enum CommandResult {
    /**
     * Команда применена, включая закрепление и выпуск следующей фигуры.
     */
    APPLIED,
    /**
     * Боковой сдвиг или поворот отклонён без изменения размещения.
     */
    BLOCKED,
    /**
     * Партия уже завершена, команда сохранила прежний снимок.
     */
    FINISHED
}
